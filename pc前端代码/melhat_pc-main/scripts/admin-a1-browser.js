async (page) => {
  const base = page.url().split('/').slice(0, 3).join('/'), requests = [], sockets = [], errors = []
  page.on('request', r => requests.push(r.url())); page.on('websocket', s => sockets.push(s.url())); page.on('pageerror', e => errors.push(e.message))
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const button = name => page.getByRole('button', { name, exact: true })
  const nav = name => page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name, exact: true }).click()
  const tab = name => page.getByRole('navigation', { name: '工作区导航' }).getByRole('link', { name, exact: true }).click()
  const row = name => page.locator('tbody tr').filter({ has: page.getByRole('button', { name, exact: true }) })
  async function login(name) { await page.getByRole('radio', { name: new RegExp(name) }).check(); await button('进入管理中心').click() }
  async function ready(name) { await button('新增' + name).waitFor(); await page.getByText('正在加载…', { exact: true }).waitFor({ state: 'hidden' }) }
  async function save() { await button('保存模拟记录').click(); await page.waitForFunction(() => !document.querySelector('dialog[open] .master-form') || Array.from(document.querySelectorAll('dialog[open] h2')).some(e => e.textContent === '确认授权效果')); if (await button('确认授权生效').count()) await button('确认授权生效').click(); await page.locator('dialog[open] .master-form').waitFor({ state: 'hidden' }) }
  async function create(name, code, title) {
    await button('新增' + name).click(); if (code) await page.getByLabel('编号', { exact: true }).fill(code)
    await page.getByLabel('名称 / 姓名', { exact: true }).fill(title)
  }
  await page.evaluate(() => { window.confirm = () => true })
  await page.goto(base + '/#/admin/overview'); await page.reload()
  if (await button('退出 / 切换身份').count()) await button('退出 / 切换身份').click()
  await login('演示系统管理员'); await page.getByLabel('当前厂站').selectOption('site-empty')
  await nav('人员组织'); await ready('人员'); await tab('组织与区域'); await ready('组织')
  await button('管理区域').click(); await ready('区域')
  await create('区域', 'DEMO-A1-AREA', '演示A1检修区'); await save()
  await row('演示A1检修区').waitFor()
  await button('管理组织').click(); await ready('组织')
  await create('组织', 'DEMO-A1-ORG', '演示A1检修班'); await page.getByLabel('所属 / 关联区域').selectOption({ label: '演示A1检修区' }); await save()
  await tab('人员档案'); await ready('人员')
  await create('人员', 'DEMO-A1-PERSON', '演示A1评审人员'); await page.getByLabel('组织 / 班组').selectOption({ label: '演示A1检修班' }); await page.getByLabel('所属 / 关联区域').selectOption({ label: '演示A1检修区' }); await save()
  await row('演示A1评审人员').waitFor()
  await row('演示A1评审人员').getByRole('button', { name: '查看', exact: true }).click()
  await page.getByRole('heading', { name: '人员详情', exact: true }).waitFor()
  await page.getByRole('link', { name: '返回人员列表', exact: true }).click(); await ready('人员')
  await button('新增人员').click(); await button('保存模拟记录').click()
  await page.getByText('请填写名称 / 姓名', { exact: true }).first().waitFor()
  await page.getByLabel('名称 / 姓名', { exact: true }).fill('演示未保存')
  await page.evaluate(() => { window.__originalConfirm = window.confirm; window.confirm = () => false }); await button('关闭面板').click()
  check(await page.locator('dialog[open] .master-form').count() === 1, 'dirty form lost on cancel')
  await page.evaluate(() => { window.confirm = () => true }); await button('取消').click()
  await page.evaluate(() => { window.confirm = window.__originalConfirm; delete window.__originalConfirm })
  await tab('班次名册'); await ready('班次'); await create('班次', null, '演示A1未来班次')
  await page.getByLabel('开始时间', { exact: true }).fill('2030-01-01T08:00'); await page.getByLabel('结束时间', { exact: true }).fill('2030-01-01T16:00')
  await page.getByRole('checkbox', { name: /演示A1评审人员/ }).check(); await save()
  await tab('人员档案'); await ready('人员'); await row('演示A1评审人员').getByRole('button', { name: '停用', exact: true }).click()
  await page.getByText(/当前或未来名册：演示A1未来班次/).waitFor(); check(await button('确认操作').isDisabled(), 'referenced person may be disabled')
  await button('保留记录').click()
  await nav('权限协作'); await ready('账号')
  await create('账号', null, '演示A1无授权账号'); await page.getByLabel('登录名', { exact: true }).fill('demo-a1-user'); await page.getByLabel('关联人员（可不关联）').selectOption({ label: '演示A1评审人员 · DEMO-A1-PERSON' }); await save()
  await row('演示A1无授权账号').waitFor()
  await button('退出 / 切换身份').click(); await login('演示A1无授权账号')
  await page.getByText(/尚未分配授权。请退出后选择管理员/).waitFor()
  await button('退出 / 切换身份').click(); await login('演示系统管理员')
  await page.getByLabel('当前厂站').selectOption('site-empty'); await nav('权限协作'); await ready('账号')
  await row('演示A1无授权账号').getByRole('button', { name: '编辑', exact: true }).click()
  await button('添加角色范围').click(); await page.getByRole('combobox', { name: '角色', exact: true }).selectOption('viewer')
  await page.getByLabel('厂站范围（Ctrl / ⌘ 多选）').selectOption(['site-1']); await save()
  await button('退出 / 切换身份').click(); await login('演示A1无授权账号')
  await page.getByLabel('当前厂站').locator('option[value="site-1"]').waitFor({ state: 'attached' })
  check(await page.getByLabel('当前厂站').locator('option').count() === 1, 'custom account scope')
  check(await page.getByLabel('当前厂站').inputValue() === 'site-1', 'wrong site after grant')
  await nav('人员组织'); await ready('人员'); check(await button('新增人员').isDisabled(), 'readonly write button')
  await button('退出 / 切换身份').click(); await login('演示系统管理员')
  await page.getByLabel('当前厂站').selectOption('site-empty'); await nav('人员组织'); await ready('人员')
  for (const [width, height] of [[1440, 900], [1672, 941], [1920, 1080]]) {
    await page.setViewportSize({ width, height }); await page.evaluate(() => scrollTo(0, 0))
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'people page overflow')
    await page.screenshot({ path: `output/playwright/admin-a1/people-${width}.png` })
    await row('演示A1评审人员').getByRole('button', { name: '编辑', exact: true }).click()
    await page.screenshot({ path: `output/playwright/admin-a1/person-editor-${width}.png` }); await button('取消').click()
    await tab('组织与区域'); await ready('组织'); await page.screenshot({ path: `output/playwright/admin-a1/trees-${width}.png` })
    await tab('人员档案'); await ready('人员')
  }
  await nav('权限协作'); await ready('账号'); await tab('基础角色'); await ready('角色')
  await create('角色', null, '演示A1区域查看角色')
  await page.getByRole('checkbox', { name: '人员查看', exact: true }).check()
  await page.getByRole('checkbox', { name: '所选厂站全部区域', exact: true }).uncheck()
  await page.getByRole('listbox', { name: '限定区域', exact: true }).selectOption({ label: '演示A1检修区 · site-empty' })
  await save(); await row('演示A1区域查看角色').waitFor()
  await page.reload(); await ready('角色')
  check(await row('演示A1区域查看角色').count() === 0, 'refresh did not reset data')
  await button('退出 / 切换身份').click()
  check(await page.getByRole('radio', { name: /演示A1无授权账号/ }).count() === 0, 'custom identity survived refresh')
  check(errors.length === 0, 'page errors: ' + errors.join(';'))
  check(requests.every(url => url.startsWith(base + '/') || url.startsWith('data:')), 'external network')
  check(!requests.some(url => /\/dev-api|\/api\/|agora|\.mp4|\.flv/i.test(url)), 'business/media request')
  if (base.endsWith(':5182')) check(sockets.length === 0, 'preview websocket')
  return { passed: true, base, requests: requests.length, sockets, errors, viewports: 3 }
}
